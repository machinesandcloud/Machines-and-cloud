// Publish browser assets only. Keep functions, business setup, evidence and credentials off the CDN.
// https://docs.netlify.com/build/functions/configuration/
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, copyFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(root, 'dist'), marker = '.mc-static-output';
if (existsSync(output) && !existsSync(resolve(output, marker))) throw new Error('Refusing to replace an unrecognized dist directory');
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
writeFileSync(resolve(output, marker), 'Generated by scripts/build-site.mjs\n');
const names = new Set(['_headers', '_redirects', 'robots.txt', 'llms.txt', 'llms-full.txt', 'rss.xml', 'sitemap.xml', 'script.js', 'hero-photos.js', 'stories.js', 'practice-voice.js', 'agent-widget.js', 'signup-intake.js', 'embed.js', 'onboard.js', 'desk.js', 'desk-requests.js', 'desk-activity.js', 'desk-conversations.js', 'desk-connections.js', 'desk-lead-sources.js', 'desk-billing.js', 'admin.js']);
const manifest = {};
function copy(relative) {
  const source = resolve(root, relative), destination = resolve(output, relative);
  mkdirSync(dirname(destination), { recursive: true });
  copyFileSync(source, destination);
  const hash = value => createHash('sha256').update(value).digest('hex');
  manifest[relative] = hash(readFileSync(source));
  if (manifest[relative] !== hash(readFileSync(destination))) throw new Error('Static copy differs: ' + relative);
}
for (const entry of readdirSync(root, { withFileTypes: true })) {
  if ((/\.(?:html|css)$/.test(entry.name) || names.has(entry.name)) && entry.isSymbolicLink()) throw new Error('Public file must not be a symlink: ' + entry.name);
  if (entry.isFile() && (/\.(?:html|css)$/.test(entry.name) || names.has(entry.name))) copy(entry.name);
}
function assets(relative) {
  for (const entry of readdirSync(resolve(root, relative), { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const path = relative + '/' + entry.name;
    if (entry.isSymbolicLink()) throw new Error('Public asset must not be a symlink: ' + path);
    if (entry.isDirectory()) assets(path); else if (entry.isFile()) copy(path);
  }
}
assets('assets');
for (const name of names) if (!manifest[name]) throw new Error('Missing required public file: ' + name);
for (const name of ['index.html', 'onboard.html', 'desk.html', 'privacy-policy.html', 'sms-terms.html', '404.html']) if (!manifest[name]) throw new Error('Missing required public page: ' + name);
// Fail if a local HTML dependency was omitted from the public package. Routes/anchors are not files.
for (const name of Object.keys(manifest).filter(name => name.endsWith('.html'))) {
  const html = readFileSync(resolve(output, name), 'utf8');
  for (const match of html.matchAll(/(?:src|href)=["']([^"']+)["']/g)) {
    const value = match[1].split(/[?#]/)[0];
    if (!value || /^(?:[a-z]+:|\/\/)/i.test(value) || !/\.(?:js|css|png|jpe?g|svg|webp|ico|pdf|woff2?)$/i.test(value)) continue;
    if (!manifest[value.replace(/^\//, '')]) throw new Error('Unpackaged browser dependency: ' + name + ' -> ' + value);
  }
}
for (const forbidden of ['product', 'scratchpad', 'scripts', 'netlify', 'node_modules', '.env', '.env.example', 'package.json', 'CLAUDE.md', 'OPERATIONS.md']) {
  if (existsSync(resolve(output, forbidden))) throw new Error('Internal file in public output: ' + forbidden);
}
const report = { at: new Date().toISOString(), output: 'dist', html: Object.keys(manifest).filter(name => name.endsWith('.html')).length, files: Object.keys(manifest).length, sourceAndOutputHashes: manifest, internalDirectoriesAbsent: true, outboundRequests: 0 };
if (existsSync(resolve(root, 'scratchpad'))) writeFileSync(resolve(root, 'scratchpad/public-build-manifest.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ ok: true, output: 'dist', html: report.html, files: report.files, internalDirectoriesAbsent: true }));
